# Основное преимущество queue.Queue перед обычным списком — это потокобезопасность (thread-safety).

"""
1. Потокобезопасность
queue.Queue предназначен для использования в многопоточных приложениях. Все его методы 
(put(), get(), empty(), full()) атомарны и синхронизированы внутренними блокировками — 
вы можете безопасно вызывать их из нескольких потоков одновременно без риска гонок данных.
Список (list) не потокобезопасен. Если несколько потоков одновременно добавляют или удаляют элементы из списка, 
это может привести к повреждению данных или исключениям.

2. Блокирующие операции
queue.Queue поддерживает блокирующие и неблокирующие операции:
queue.get(block=True) — ожидает, пока элемент появится (если очередь пуста).
queue.put(item, block=True) — ожидает, пока будет свободное место (если очередь полна).
Это позволяет легко реализовывать паттерны "производитель-потребитель" без ручной синхронизации.
Список не имеет встроенной логики ожидания — вам придётся вручную использовать threading.Condition 
или другие механизмы для синхронизации.

3. Ограниченная ёмкость
queue.Queue(maxsize=N) позволяет ограничить размер очереди — полезно для управления нагрузкой 
и предотвращения переполнения памяти.
Список не имеет встроенного лимита — вы можете добавлять элементы до тех пор, пока не кончится память.

4. Чёткий интерфейс
queue.Queue предоставляет чётко определённый интерфейс для FIFO-очереди: put(), get(), qsize(), empty(), full().
Работа со списком как с очередью (например, list.append() + list.pop(0)) неэффективна — 
pop(0) требует O(n) времени, так как все элементы сдвигаются.
"""

# Паттерн producer-consumer

import queue
import threading
import time


# Для исключения зависания задач, если забыли вызвать task_done - обёртка в контекстный менеджер
class _TaskContext():
    def __init__(self, q: queue.Queue):
        self.q = q

    def __enter__(self):
        item = self.q.get()
        return item

    def __exit__(self, *args):
        self.q.task_done()


class TaskQueue(queue.Queue):
    def task(self):
        return _TaskContext(self)


q = TaskQueue()

# Функция производителя
def producer():
    for i in range(5):
        item = f"Задача {i}"
        q.put(item)
        print(f"Добавлено в очередь: {item}")
        time.sleep(0.1)


# Функция потребителя
def consumer():
    while True:
        with q.task() as item:
            if item is None:
                break
            print(f"Обработано {item}")
            time.sleep(0.5)  # имитация обработки

# Запуск потоков
consumer_thread = threading.Thread(target=consumer)
consumer_thread.start()

producer()
q.put(None)  # Сигнал остановки потребителя ?
consumer_thread.join()












